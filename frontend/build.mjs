// Copies pinned browser assets into the package and generates icons.js.
// Run through `make assets` (npm ci + this script + the Tailwind build).
// Everything written here is committed, so the Python package never needs Node.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkg = join(here, "..", "src", "mail_cadence");
const templatesDir = join(pkg, "web_templates");
const staticDir = join(pkg, "web_static");
const modules = join(here, "node_modules");

const GENERATED = new Set(["icons.js"]);

function version(name) {
  return JSON.parse(readFileSync(join(modules, name, "package.json"), "utf8")).version;
}

function copy(from, to) {
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
}

// 1. Vendored files and their licenses.
copy(join(modules, "htmx.org", "dist", "htmx.min.js"), join(staticDir, "vendor", "htmx.min.js"));
for (const [font, file] of [
  ["inter", "inter-latin-wght-normal.woff2"],
  ["jetbrains-mono", "jetbrains-mono-latin-wght-normal.woff2"],
]) {
  const fontPkg = join(modules, "@fontsource-variable", font);
  copy(join(fontPkg, "files", file), join(staticDir, "fonts", file));
  copy(join(fontPkg, "LICENSE"), join(staticDir, "licenses", `${font}-OFL.txt`));
}
copy(join(modules, "htmx.org", "LICENSE"), join(staticDir, "licenses", "htmx-0BSD.txt"));
copy(join(modules, "lucide", "LICENSE"), join(staticDir, "licenses", "lucide-ISC.txt"));

// 2. icons.js with only the icons the panel uses (`<i data-lucide="name">`).
const sources = [
  ...readdirSync(templatesDir).filter((f) => f.endsWith(".html")).map((f) => join(templatesDir, f)),
  ...readdirSync(staticDir)
    .filter((f) => f.endsWith(".js") && !GENERATED.has(f))
    .map((f) => join(staticDir, f)),
];
const names = new Set();
for (const file of sources) {
  for (const match of readFileSync(file, "utf8").matchAll(/data-lucide="([a-z0-9-]+)"/g)) {
    names.add(match[1]);
  }
}
const { icons } = require("lucide");
const toPascal = (name) =>
  name.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
const used = {};
for (const name of [...names].sort()) {
  const node = icons[toPascal(name)];
  if (!node) throw new Error(`Unknown lucide icon: ${name}`);
  used[name] = node;
}
const iconsJs = `// Generated by frontend/build.mjs from lucide@${version("lucide")} (ISC license). Do not edit.
"use strict";
(() => {
  const SVG_NS = "http://www.w3.org/2000/svg";
  const DEFAULTS = {
    xmlns: SVG_NS, width: "24", height: "24", viewBox: "0 0 24 24", fill: "none",
    stroke: "currentColor", "stroke-width": "2", "stroke-linecap": "round",
    "stroke-linejoin": "round", "aria-hidden": "true",
  };
  const ICONS = ${JSON.stringify(used)};

  function render(root) {
    for (const el of (root || document).querySelectorAll("i[data-lucide]")) {
      const name = el.getAttribute("data-lucide");
      const node = ICONS[name];
      if (!node) {
        console.warn("Unknown icon:", name);
        continue;
      }
      const svg = document.createElementNS(SVG_NS, "svg");
      for (const [key, value] of Object.entries(DEFAULTS)) svg.setAttribute(key, value);
      for (const attr of el.attributes) {
        if (attr.name !== "class" && attr.name !== "data-lucide") svg.setAttribute(attr.name, attr.value);
      }
      svg.setAttribute("class", ["lucide", "lucide-" + name, el.getAttribute("class") || ""].join(" ").trim());
      for (const [tag, attrs] of node) {
        const child = document.createElementNS(SVG_NS, tag);
        for (const [key, value] of Object.entries(attrs)) child.setAttribute(key, value);
        svg.appendChild(child);
      }
      el.replaceWith(svg);
    }
  }

  window.MailCadenceIcons = { render };
})();
`;
writeFileSync(join(staticDir, "icons.js"), iconsJs);

console.log(
  `htmx.org@${version("htmx.org")}, lucide@${version("lucide")} (${names.size} icons), ` +
    `fonts @fontsource-variable/inter@${version("@fontsource-variable/inter")}, ` +
    `@fontsource-variable/jetbrains-mono@${version("@fontsource-variable/jetbrains-mono")}`,
);
